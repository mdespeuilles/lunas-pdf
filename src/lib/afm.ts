/** Code WinAnsi d'un caractère (« ? » s'il n'existe pas, comme dans l'apparence). */
export function winansi(ch: string): number {
  const u = ch.codePointAt(0) ?? 63;
  if ((u >= 0x20 && u <= 0x7e) || (u >= 0xa0 && u <= 0xff)) return u;
  return SPECIALS[u] ?? 63;
}

export function textWidth(text: string, font: FontFamily, size: number): number {
  let w = 0;
  for (const ch of text) w += W[font][winansi(ch)];
  return (w * size) / 1000;
}

/** Même algorithme que `appearance::wrap` (Rust). */
export function wrap(text: string, font: FontFamily, size: number, width: number): string[] {
  const lines: string[] = [];
  for (const para of text.split("\n")) {
    let line = "";
    for (const word of para.split(" ")) {
      const candidate = line ? `${line} ${word}` : word;
      if (textWidth(candidate, font, size) <= width || (!line && textWidth(word, font, size) <= width)) {
        line = candidate;
        continue;
      }
      if (line) {
        lines.push(line);
        line = "";
      }
      for (const ch of word) {
        if (textWidth(line + ch, font, size) > width && line) {
          lines.push(line);
          line = "";
        }
        line += ch;
      }
    }
    lines.push(line);
  }
  return lines;
}

export const FREETEXT_PAD = 2;
export const FREETEXT_LEADING = 1.2;

/**
 * Taille d'une zone de texte pour son contenu : largeur de la plus longue ligne (bornée par
 * `maxWidth`), hauteur du nombre de lignes après coupure. `minText` : texte de référence
 * pour une zone vide (le texte indicatif reste visible).
 */
export function fitTextBox(text: string, font: FontFamily, size: number, maxWidth: number, minText = ""): { w: number; h: number } {
  const longest = Math.max(...(text || minText).split("\n").map((l) => textWidth(l, font, size)), size);
  const w = Math.min(longest + 2 * FREETEXT_PAD + 1, Math.max(maxWidth, size + 2 * FREETEXT_PAD));
  const lines = wrap(text, font, size, w - 2 * FREETEXT_PAD).length;
  return { w, h: lines * size * FREETEXT_LEADING + 2 * FREETEXT_PAD };
}
